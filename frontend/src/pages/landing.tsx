function HeroSignalsCard() {
  const rotateX = useMotionValue(12);
  const rotateY = useMotionValue(-18);
  const springX = useSpring(rotateX, { stiffness: 140, damping: 18, mass: 0.6 });
  const springY = useSpring(rotateY, { stiffness: 140, damping: 18, mass: 0.6 });

  function onMove(event: PointerEvent<HTMLDivElement>) {
    const rect = event.currentTarget.getBoundingClientRect();
    const px = (event.clientX - rect.left) / rect.width - 0.5;
    const py = (event.clientY - rect.top) / rect.height - 0.5;
    rotateX.set(12 - py * 10);
    rotateY.set(-18 + px * 12);
  }

  function onLeave() {
    rotateX.set(12);
    rotateY.set(-18);
  }

  return (
    <motion.div
      className="hero-scene relative mx-auto w-full max-w-xl lg:max-w-none"
      initial={{ opacity: 0, y: 28 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.8, delay: 0.12, ease }}
    >
      <div className="pointer-events-none absolute -bottom-10 left-10 right-6 h-20 rounded-full bg-violet-500/20 blur-3xl" />
      <motion.div
        onPointerMove={onMove}
        onPointerLeave={onLeave}
        style={{
          rotateX: springX,
          rotateY: springY,
          rotateZ: 2,
          transformStyle: "preserve-3d",
        }}
        className="hero-signals-card glass relative rounded-[28px] p-5 sm:p-6"
      >
        <div className="mb-4 flex items-center justify-between gap-3 text-sm text-white/55">
          <span>Screener · Top Signals</span>
          <LiveBadge />
          <span className="text-xs">48 matches</span>
        </div>
        <div className="grid grid-cols-[1.3fr_0.9fr_0.7fr_0.7fr] px-2 pb-2 text-[10px] font-medium uppercase tracking-[0.16em] text-white/35">
          <span>Ticker</span>
          <span>7-Day Trend</span>
          <span className="text-right">Price</span>
          <span className="text-right">Change</span>
        </div>
        <div className="signals-window">
          <div className="signals-track">
            {LOOPED_SIGNALS.map((row, index) => (
              <SignalRow key={`${row.symbol}-${index}`} row={row} />
            ))}
          </div>
        </div>
      </motion.div>
    </motion.div>
  );
}

